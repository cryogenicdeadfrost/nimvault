# Regenerates src/nimvault/private/bearssl_sources.nim from src/nimvault/vendor/bearssl/src/**/*.c

import std/[os, algorithm, strutils]

proc spitSources() =
  let repoRoot = currentSourcePath.parentDir.parentDir
  let bearSrc = repoRoot / "src" / "nimvault" / "vendor" / "bearssl" / "src"
  let outFile = repoRoot / "src" / "nimvault" / "private" / "bearssl_sources.nim"

  var files: seq[string] = @[]
  for path in walkDirRec(bearSrc):
    if path.endsWith(".c"):
      files.add(relativePath(path, outFile.parentDir).replace('\\', '/'))
  files.sort()

  var lines: seq[string] = @[
    "# generated by tools/gen_bearssl_sources.nim -- don't hand-edit 277 lines unless you enjoy pain",
    "",
    "import std/[os, strutils]",
    "",
    "const",
    "  bearRoot = currentSourcePath.parentDir / \"..\" / \"vendor\" / \"bearssl\"",
    "  bearInc = (bearRoot / \"inc\").replace('\\\\', '/')",
    "  bearSrcDir = (bearRoot / \"src\").replace('\\\\', '/')",
    "",
    "{.passC: \"-I\\\"\" & bearInc & \"\\\"\".}",
    "{.passC: \"-I\\\"\" & bearSrcDir & \"\\\"\".}",
    "",
    "when defined(windows):",
    "  {.passL: \"-ladvapi32\".}",
    "",
    "{.compile: \"bearssl_shim.c\".}",
    ""
  ]

  for f in files:
    lines.add("{.compile: \"" & f & "\".}")

  createDir(outFile.parentDir)
  writeFile(outFile, lines.join("\n") & "\n")
  echo "wrote ", outFile, " (", files.len, " C files)"

when isMainModule:
  spitSources()
