## Helper script to regenerate src/nimvault/private/bearssl_sources.nim
## from vendor/bearssl/src/**/*.c for zero-CMake {.compile.} static vendoring.

import std/[os, algorithm, strutils]

proc main() =
  let repoRoot = currentSourcePath.parentDir.parentDir
  let bearsslSrc = repoRoot / "vendor" / "bearssl" / "src"
  let outFile = repoRoot / "src" / "nimvault" / "private" / "bearssl_sources.nim"

  var cFiles: seq[string] = @[]
  for path in walkDirRec(bearsslSrc):
    if path.endsWith(".c"):
      let rel = relativePath(path, outFile.parentDir).replace('\\', '/')
      cFiles.add(rel)

  cFiles.sort()

  var lines: seq[string] = @[
    "## Auto-generated by tools/gen_bearssl_sources.nim",
    "## Compiles vendored BearSSL 0.6 C sources statically via Nim {.compile.} pragmas.",
    "## No CMake, Make, or system OpenSSL required.",
    "",
    "import std/[os, strutils]",
    "",
    "const",
    "  bearsslRoot = currentSourcePath.parentDir / \"..\" / \"..\" / \"..\" / \"vendor\" / \"bearssl\"",
    "  bearsslInc = (bearsslRoot / \"inc\").replace('\\\\', '/')",
    "  bearsslSrcDir = (bearsslRoot / \"src\").replace('\\\\', '/')",
    "",
    "{.passC: \"-I\\\"\" & bearsslInc & \"\\\"\".}",
    "{.passC: \"-I\\\"\" & bearsslSrcDir & \"\\\"\".}",
    "",
    "when defined(windows):",
    "  {.passL: \"-ladvapi32\".}",
    "",
    "{.compile: \"bearssl_shim.c\".}",
    ""
  ]

  for f in cFiles:
    lines.add("{.compile: \"" & f & "\".}")

  createDir(outFile.parentDir)
  writeFile(outFile, lines.join("\n") & "\n")
  echo "Generated ", outFile, " with ", cFiles.len, " BearSSL C sources."

when isMainModule:
  main()
